CREATE DATABASE ECOMMERCE_DB;

CREATE SCHEMA RAW;

CREATE SCHEMA TRANSFORM;

CREATE SCHEMA ANALYTICS;

CREATE STORAGE INTEGRATION S3_INT
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = S3
ENABLED = TRUE
STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::654654610219:role/mys3role'
STORAGE_ALLOWED_LOCATIONS =
('s3://my-snowflake-project-data/');

ALTER STORAGE INTEGRATION S3_INT
SET STORAGE_ALLOWED_LOCATIONS = (
    's3://my-snowflake-project1-data/'
);


DESC INTEGRATION S3_INT;

CREATE STAGE ECOMMERCE_S3_STAGE1
URL = 's3://my-snowflake-project1-data/'
STORAGE_INTEGRATION = S3_INT;

LIST @ECOMMERCE_S3_STAGE1;

CREATE FILE FORMAT CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE TABLE RAW.CUSTOMERS (
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR,
    EMAIL VARCHAR,
    CITY VARCHAR,
    LOAD_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

alter table raw.orders drop column LOAD_TIMESTAMP;

CREATE TABLE RAW.ORDERS (
    ORDER_ID NUMBER,
    CUSTOMER_ID NUMBER,
    PRODUCT_ID NUMBER,
    QUANTITY NUMBER,
    ORDER_AMOUNT NUMBER(10,2),
    ORDER_DATE DATE,
    LOAD_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP()   
);

COPY INTO RAW.CUSTOMERS
FROM @ECOMMERCE_S3_STAGE1/customers/
FILE_FORMAT = CSV_FORMAT;

COPY INTO RAW.orders
FROM @ECOMMERCE_S3_STAGE1/orders/
FILE_FORMAT = CECOMMERCE_DB.RAW.ORDERSSV_FORMAT;

SELECT * FROM RAW.CUSTOMERS;

SELECT *
FROM INFORMATION_SCHEMA.COPY_HISTORY;

CREATE PIPE CUSTOMERS_PIPE
AUTO_INGEST = TRUE
AS
COPY INTO RAW.CUSTOMERS
FROM @ECOMMERCE_S3_STAGE1/customers/
FILE_FORMAT = CSV_FORMAT;

DESC PIPE CUSTOMERS_PIPE;
